    /// <summary>
    /// The night foreman: he staffs only the machine he gives the job to, he does not offer a job straight back to
    /// the machine that handed it in, and he judges a climb by what the machine can hold in the snow lying there.
    /// </summary>
    [TestFixture]
    public sealed class ForemanDispatchTests
    {
        private static AlpineSim.Core.Data.GameData Data()
        {
            var data = TestEnv.FreshData();
            data.Tuning.Override("tasks.autoDispatch", 0f); // these tests call the foreman by hand
            return data;
        }

        private static VehicleState Cat(Simulation sim)
        {
            foreach (var v in sim.World.Vehicles.List) if (v.DefId == "groomer_mid") return v;
            Assert.Fail("test_small has no groomer_mid");
            return null;
        }

        /// <summary>Everyone but the named operator is taken off the roster, so the fleet holds exactly one cat driver.</summary>
        private static OperatorState OnlyCatDriver(Simulation sim)
        {
            var f = sim.World.Fleet;
            OperatorState keep = null;
            foreach (var o in f.Operators) if (!o.IsPlayer && o.Has(OperatorLicense.Groomer)) { keep = o; break; }
            Assert.IsNotNull(keep, "test_small has no groomer-licensed operator");
            for (int i = f.Operators.Count - 1; i >= 0; i--)
            {
                var o = f.Operators[i];
                if (o.IsPlayer || o.Id == keep.Id) continue;
                f.Operators.RemoveAt(i);
            }
            return keep;
        }

        /// <summary>
        /// Two cats, one licensed driver, one grooming job: the job goes out. Staffing every candidate during the
        /// scan used to shuffle the one driver from cat to cat, and the cat finally picked had lost her again, so the
        /// job stayed open night after night with a driver parked at the depot.
        /// </summary>
        [Test]
        public void OneDriverAndTwoCatsStillGetsTheJobOut()
        {
            var sim = Simulation.CreateNew(Data(), 41, "test_small");
            var ctx = sim.Ctx;
            var ts = sim.GetSystem<TaskSystem>();
            var vs = sim.GetSystem<VehicleSystem>();
            OnlyCatDriver(sim);

            // the second cat stands FARTHER from the run than the first, so the nearest-wins scan picks the first.
            // That is the case the old scan broke on: staffing each candidate in turn moved the one driver off the
            // first cat and into the second, and the first - the one the scan then picked - had nobody in it.
            var first = Cat(sim);
            var piste = sim.World.Pistes.Piste("t1");
            var site = piste.Points[piste.Points.Count - 1];
            var away = (first.Pos - site).Normalized;
            var second = vs.Spawn(ctx, "groomer_mid", first.Pos + away * 60f, 0f, "Second Cat");
            Assert.AreEqual(-1, first.OperatorId);
            Assert.AreEqual(-1, second.OperatorId);
            Assert.Less(Vec2.Distance(first.Pos, site), Vec2.Distance(second.Pos, site), "the first cat must be the nearer one");

            // top priority so it outranks the road and lot work the sim posts on its own
            var task = ts.Create(ctx, TaskKind.Groom, "Groom " + piste.Name, site, "t1", -1, 1f, 9f);
            task.AutoGenerated = true;

            ts.AutoDispatch(ctx);
            Assert.AreNotEqual(-1, task.AssignedVehicleId, "the foreman should give the job to one of the two cats");
            Assert.AreEqual(TaskStatus.InProgress, task.Status);

            var sent = task.AssignedVehicleId == first.Id ? first : second;
            Assert.AreNotEqual(-1, task.AssignedVehicleId, "the job was assigned to no machine");
            Assert.AreNotEqual(-1, sent.OperatorId, "the cat that got the job has nobody in it");
            var op = sim.World.Fleet.Operator(sent.OperatorId);
            Assert.IsTrue(op.Has(OperatorLicense.Groomer), "the cat that got the job holds an unlicensed operator");

            var idle = sent.Id == first.Id ? second : first;
            Assert.AreEqual(-1, idle.OperatorId, "the driver was left sitting in the cat that did not get the job");
        }

        /// <summary>A machine that hands a job in is not offered it again on the same shift: it would drive to the same pitch and stall there again.</summary>
        [Test]
        public void AJobHandedInIsNotOfferedBackToTheSameMachine()
        {
            var sim = Simulation.CreateNew(Data(), 42, "test_small");
            var ctx = sim.Ctx;
            var ts = sim.GetSystem<TaskSystem>();
            var fs = sim.GetSystem<FleetSystem>();
            var cat = Cat(sim);
            OnlyCatDriver(sim);

            var piste = sim.World.Pistes.Piste("t1");
            var task = ts.Create(ctx, TaskKind.Groom, "Groom " + piste.Name, piste.Points[piste.Points.Count - 1], "t1", -1, 1f, 9f);
            task.AutoGenerated = true;

            ts.AutoDispatch(ctx);
            Assert.AreEqual(cat.Id, task.AssignedVehicleId);

            // the cat gives it back on a pitch it cannot climb
            ts.Unassign(ctx, task.Id);
            ts.Block(ctx, task.Id, cat.Name + ": cannot climb the 22 deg pitch", cat.Id);
            Assert.AreEqual(cat.Id, task.BlockedByVehicleId);

            // the retry timer runs out and the job goes back on the board, but not to that cat
            ts.Unblock(ctx, task.Id);
            Assert.AreEqual(TaskStatus.Open, task.Status);
            ts.AutoDispatch(ctx);
            Assert.AreEqual(-1, task.AssignedVehicleId, "the cat that handed the job in was sent straight back to it");

            // by the next shift it is offered again
            sim.StepHours(ctx.Tuning.F("tasks.blockRetrySameMachineHours") + 0.5);
            Assert.AreEqual(TaskStatus.Open, task.Status, "the job should still be open");
            ts.AutoDispatch(ctx);
            Assert.AreEqual(cat.Id, task.AssignedVehicleId, "after the shift window the cat should be offered the job again");
        }

        /// <summary>
        /// A later block for another reason - a wind hold, a machine throwing a track on the same job - must not erase
        /// the record of which machine handed the job in, nor restart its clock.
        /// </summary>
        [Test]
        public void AWeatherHoldDoesNotEraseTheSameMachineHold()
        {
            var sim = Simulation.CreateNew(Data(), 49, "test_small");
            var ctx = sim.Ctx;
            var ts = sim.GetSystem<TaskSystem>();
            var cat = Cat(sim);
            OnlyCatDriver(sim);

            var piste = sim.World.Pistes.Piste("t1");
            var task = ts.Create(ctx, TaskKind.Groom, "Groom " + piste.Name, piste.Points[piste.Points.Count - 1], "t1", -1, 1f, 9f);
            task.AutoGenerated = true;

            ts.Block(ctx, task.Id, cat.Name + ": cannot climb the 22 deg pitch", cat.Id);
            long handedIn = task.BlockedByTick;
            Assert.AreEqual(cat.Id, task.BlockedByVehicleId);
            Assert.GreaterOrEqual(handedIn, 0L);

            sim.StepMinutes(30);
            ts.Block(ctx, task.Id, "weather: wind hold"); // names no machine
            Assert.AreEqual(cat.Id, task.BlockedByVehicleId, "the wind hold erased the record of who handed the job in");
            Assert.AreEqual(handedIn, task.BlockedByTick, "the wind hold restarted the same-machine clock");

            ts.Unblock(ctx, task.Id);
            ts.AutoDispatch(ctx);
            Assert.AreEqual(-1, task.AssignedVehicleId, "the cat that handed the job in should still be held out");
        }

        /// <summary>A job blocked for a reason that is nobody's machine (weather, parts) is not excluded from any machine.</summary>
        [Test]
        public void AJobBlockedWithoutAMachineIsOfferedToEveryone()
        {
            var sim = Simulation.CreateNew(Data(), 43, "test_small");
            var ctx = sim.Ctx;
            var ts = sim.GetSystem<TaskSystem>();
            var cat = Cat(sim);
            OnlyCatDriver(sim);

            var piste = sim.World.Pistes.Piste("t1");
            var task = ts.Create(ctx, TaskKind.Groom, "Groom " + piste.Name, piste.Points[piste.Points.Count - 1], "t1", -1, 1f, 9f);
            task.AutoGenerated = true;
            ts.Block(ctx, task.Id, "weather: wind hold"); // no machine named
